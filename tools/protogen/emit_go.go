package main

import (
	"fmt"
	"go/format"
	"strings"
)

// header names the generator and the schema, in the form go vet and the
// linters take for generated code.
func (s schema) header() string {
	return "Code generated by go run ./tools/protogen from " + s.source + "; DO NOT EDIT."
}

// width is where a generated comment wraps.
const width = 96

// emitGo writes the Go side: the paths, the bounds, and a type per definition,
// in the shape encoding/json decodes the mod's requests into. An optional
// field is a pointer, or a slice, so absent and zero stay apart.
func emitGo(s schema) ([]byte, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\n\npackage %s\n", s.header(), s.goPackage)
	if len(s.endpoints) > 0 {
		b.WriteString("\n// The paths of the protocol's endpoints, each a POST.\nconst (\n")
		for _, e := range s.endpoints {
			name := "Path" + upperCamel(strings.Split(e.path, "/"))
			writeComment(&b, "\t// ", fmt.Sprintf("%s %s Asked %s, answered %s.", name, e.description, e.request, e.answer))
			fmt.Fprintf(&b, "\t%s = %q\n", name, "/v1/"+e.path)
		}
		b.WriteString(")\n")
	}
	if len(s.bounds) > 0 {
		b.WriteString("\n// The protocol's bounds.\nconst (\n")
		for _, bound := range s.bounds {
			name := goName(bound.name)
			writeComment(&b, "\t// ", name+" "+bound.description)
			fmt.Fprintf(&b, "\t%s = %d\n", name, bound.value)
		}
		b.WriteString(")\n")
	}
	for _, d := range s.defs {
		b.WriteString("\n")
		writeComment(&b, "// ", d.name+" "+d.description)
		if d.enum != nil {
			fmt.Fprintf(&b, "type %s string\n\n// The values of %s.\nconst (\n", d.name, d.name)
			for _, value := range d.enum {
				fmt.Fprintf(&b, "\t%s%s %s = %q\n", d.name, goName(value), d.name, value)
			}
			b.WriteString(")\n")
			continue
		}
		if len(d.fields) == 0 {
			fmt.Fprintf(&b, "type %s struct{}\n", d.name)
			continue
		}
		fmt.Fprintf(&b, "type %s struct {\n", d.name)
		for i, f := range d.fields {
			if i > 0 {
				b.WriteString("\n")
			}
			name := goName(f.name)
			writeComment(&b, "\t// ", name+" "+f.description)
			tag := f.name
			if !f.required {
				tag += ",omitempty"
			}
			fmt.Fprintf(&b, "\t%s %s `json:%q`\n", name, goType(f), tag)
		}
		b.WriteString("}\n")
	}
	source, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("the generated Go does not parse: %w", err)
	}
	return source, nil
}

func goType(f field) string {
	base := map[string]string{"string": "string", "integer": "int", "boolean": "bool"}[f.shape.scalar]
	if f.shape.ref != "" {
		base = f.shape.ref
	}
	switch {
	case f.shape.array:
		return "[]" + base
	case !f.required:
		return "*" + base
	}
	return base
}

// initialisms are the words Go spells in capitals.
var initialisms = map[string]string{"id": "ID", "rgb": "RGB"}

// goName turns a lower camel JSON name into an exported Go one.
func goName(name string) string {
	var words []string
	start := 0
	for i, r := range name {
		if i > 0 && r >= 'A' && r <= 'Z' {
			words = append(words, name[start:i])
			start = i
		}
	}
	return upperCamel(append(words, name[start:]))
}

func upperCamel(words []string) string {
	var b strings.Builder
	for _, word := range words {
		if spelled, ok := initialisms[strings.ToLower(word)]; ok {
			b.WriteString(spelled)
			continue
		}
		b.WriteString(strings.ToUpper(word[:1]) + word[1:])
	}
	return b.String()
}

// writeComment wraps text into comment lines that begin with prefix.
func writeComment(b *strings.Builder, prefix, text string) {
	line := prefix
	for _, word := range strings.Fields(text) {
		if line != prefix && len(line)+1+len(word) > width {
			b.WriteString(strings.TrimRight(line, " ") + "\n")
			line = prefix
		}
		if line != prefix {
			line += " "
		}
		line += word
	}
	b.WriteString(line + "\n")
}
